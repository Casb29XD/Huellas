private fun localize(value: String, language: String): String {
    if (language != "en") return value
    englishCopy[value]?.let { return it }

    Regex("^Foto ([0-9]+)$").matchEntire(value)?.let { return "Photo ${it.groupValues[1]}" }
    Regex("^hace ([0-9]+) min$").matchEntire(value)?.let { return "${it.groupValues[1]} min ago" }
    Regex("^hace ([0-9]+) h$").matchEntire(value)?.let { return "${it.groupValues[1]} hr ago" }
    Regex("^hace ([0-9]+) d$").matchEntire(value)?.let { return "${it.groupValues[1]} days ago" }
    Regex("^hace ([0-9]+) sem$").matchEntire(value)?.let { return "${it.groupValues[1]} wk ago" }
    Regex("^hace ([0-9]+) mes$").matchEntire(value)?.let { return "${it.groupValues[1]} mo ago" }
    Regex("^Solicitud enviada\\. Te avisaremos cuando (.+) responda$").matchEntire(value)?.let {
        return "Request sent. We'll let you know when ${it.groupValues[1]} replies."
    }
    Regex("^Enlace enviado a (.+)$").matchEntire(value)?.let { return "Link sent to ${it.groupValues[1]}" }
    Regex("^Indica la (.+)$").matchEntire(value)?.let { return "Enter the ${it.groupValues[1].replaceFirstChar { c -> c.lowercase() }}" }
    Regex("^Nueva publicación · (.+)$").matchEntire(value)?.let { return "New post · ${it.groupValues[1]}" }
    Regex("^¡Hola, (.+)!$").matchEntire(value)?.let { return "Hello, ${it.groupValues[1]}!" }
    Regex("^La contraseña debe tener al menos ([0-9]+) caracteres$").matchEntire(value)?.let {
        return "Password must be at least ${it.groupValues[1]} characters"
    }
    Regex("^Enviamos un enlace a (.+) para que crees una nueva contraseña\\. Si no lo ves, revisa la carpeta de spam\\.$").matchEntire(value)?.let {
        return "We sent a link to ${it.groupValues[1]} to reset your password. Check your spam folder if you don't see it."
    }
    Regex("^(.+) · (.+) en (.+)\\. Míralo en Huella\\.$").matchEntire(value)?.let {
        return "${it.groupValues[1]} · ${englishCopy[it.groupValues[2]] ?: it.groupValues[2]} in ${englishCopy[it.groupValues[3]] ?: it.groupValues[3]}. View it on Huella."
    }
    Regex("^En revisión · (.+) en espera · publicado (.+)$").matchEntire(value)?.let {
        return "Under review · ${it.groupValues[1]} waiting · posted ${it.groupValues[2]}"
    }
    Regex("^Nueva publicación · (.+)$").matchEntire(value)?.let {
        return "New post · ${it.groupValues[1]}"
    }
    Regex("^(.+) cerca de (.+)$").matchEntire(value)?.let {
        return "${it.groupValues[1]} near ${englishCopy[it.groupValues[2]] ?: it.groupValues[2]}"
    }
    Regex("^Publicado por (.+)$").matchEntire(value)?.let {
        return "Posted by ${it.groupValues[1]}"
    }
    Regex("^Llamar a (.+)$").matchEntire(value)?.let {
        return "Call ${it.groupValues[1]}"
    }
    Regex("^(.+) puntos$").matchEntire(value)?.let {
        return "${it.groupValues[1]} points"
    }
    Regex("^(.+) aprobadas$").matchEntire(value)?.let {
        return "${it.groupValues[1]} approved"
    }
    Regex("^(.+) rechazadas$").matchEntire(value)?.let {
        return "${it.groupValues[1]} rejected"
    }
    Regex("^(.+) denuncias$").matchEntire(value)?.let {
        return "${it.groupValues[1]} reports"
    }
    Regex("^([0-9]+) Publicaciones$").matchEntire(value)?.let {
        return "${it.groupValues[1]} Posts"
    }
    Regex("^([0-9]+) Adopciones concretadas$").matchEntire(value)?.let {
        return "${it.groupValues[1]} Completed adoptions"
    }
    return value
}

